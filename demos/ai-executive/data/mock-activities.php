<?php

declare(strict_types=1);

/**
 * School activities for the current term with participation counts.
 */
function exe_mock_activities(int $students, array $scenario, MockRandom $rng): array
{
    $list = [
        ['กีฬาสีภายใน', 'กีฬา', '2026-06-12'], ['วันไหว้ครู', 'ประเพณี', '2026-06-18'], ['สัปดาห์ห้องสมุด', 'วิชาการ', '2026-07-08'],
        ['ค่ายภาษาอังกฤษ', 'วิชาการ', '2026-07-22'], ['วันแม่แห่งชาติ', 'ประเพณี', '2026-08-11'], ['สัปดาห์วิทยาศาสตร์', 'วิชาการ', '2026-08-18'],
        ['จิตอาสาพัฒนาชุมชน', 'จิตอาสา', '2026-08-29'], ['แข่งขันทักษะวิชาการ', 'วิชาการ', '2026-09-10'], ['ประชุมผู้ปกครอง', 'ชุมชน', '2026-09-19'],
        ['ทัศนศึกษา', 'แหล่งเรียนรู้', '2026-09-26'], ['ตลาดนัดอาชีพ', 'อาชีพ', '2026-10-03'], ['นิทรรศการผลงานนักเรียน', 'วิชาการ', '2026-10-08'],
    ];
    $rate = max(0.35, min(0.95, 0.72 + $scenario['dev'] * 0.06));

    return array_map(static fn ($a) => [
        'name'         => $a[0],
        'category'     => $a[1],
        'date'         => $a[2],
        'participants' => (int) round($students * max(0.2, min(1, $rate + $rng->gauss(0, 0.08)))),
    ], $list);
}
